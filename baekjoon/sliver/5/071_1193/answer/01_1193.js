/*

한 칸씩 움직이는 규칙(아래 → 대각선 → 오른쪽)을 알고리즘에 그대로 흉내내면 코드가 지저분해짐. (내가 한 번 삽질함;;)
조금 다르게 생각해볼 필요가 있음.

1번째 대각선: 1/1
2번째 대각선: 1/2 > 2/1    
3번째 대각선: 3/1 > 2/2 > 1/3
4번째 대각선: 1/4 > 2/3 > 3/2 > 4/1

n번째 대각선: n/1 > n-1/2 > ... > 2/n-1 > 1/n (n은 홀수)
n번째 대각선: 1/n > 2/n-1 > ... > n-1/2 > n/1 (n은 짝수)
...

대각선이 홀수이면 시작점의 분모가 1이고 분자가 1씩 줄어들며 분모는 1씩 늘어남
대각선이 짝수이서 시작점의 분자가 1이고 분자가 1씩 늘어나며 분모는 1씩 줄어듦
또 n번째 대각선에는 n개의 분수가 존재함

위 특성을 이용해 X번째 분수가 몇 번째 대각선에 있는지 찾은 후 그 대각선 내에 몇 번째 있는지만 계산하면 쉬울듯.

*/

const fs = require('fs');
const input = fs.readFileSync(0, 'utf8').trim().split(' ');

let X = +input[0];
let n = 1;

while (X > n) {
    X -= n;
    ++n;
}

const [a, b] = n % 2 === 0 ?
    [X, n + 1 - X]
    :
    [n + 1 - X, X]
;

console.log(`${a}/${b}`);
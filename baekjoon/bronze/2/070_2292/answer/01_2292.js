/*

전제조건은 방의 모양이 육각형임

처음 방 1개로 시작 (1겹)

1겹으로 이루어진 방의 모든 모서리가 새로운 방으로 둘러쌓인다면
1겹 방의 모양은 육각형이므로 각 모서리마다 한 개씩 총 6개의 방이 추가됨 (2겹)

2겹으로 이루어진 방의 모든 모서리가 새로운 방으로 둘러쌓인다면
2겹 방은 모서리가 서로 맞닿는 부분에 한 개씩 + 맞닿지 않는 부분에 한 개씩, 총 6+6개의 방이 추가됨 (3겹)

3겹으로 이루어진 방의 모든 모서리가 새로운 방으로 둘러쌓인다면
3겹 방은 모서리가 서로 맞닿는 부분에 한 개씩 + 맞닿지 않는 부분에 한 개씩, 총 12+6개의 방이 추가됨 (4겹)

아하! 겹의 개수를 n이라고 하면 n>1일 때 각 겹이 가지는 방의 개수는 6*(n-1)이 되는구나!

1겹: 1개    > 총 1개
2겹: 6개    > 총 7개
3겹: 12개   > 총 19개
4겹: 18개   > 총 37개
...

1번 방에서 N번 방까지 최소로 지나는 방의 개수는 N번 방이 속한 겹의 개수 n과 같다.
따라서 N이 몇 겹에 있는지 찾으면 된다~

*/

const fs = require('fs');
const input = fs.readFileSync(0, 'utf8').trim().split(' ');

let N = +input[0];

let n = 1, last = 1;
while (N > last) {
    ++n;
    last += 6*(n-1);
}

console.log(n);

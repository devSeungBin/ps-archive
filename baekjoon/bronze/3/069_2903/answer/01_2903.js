/*

나는 간단하게 각 가로줄당 점을 몇 번씩 찍어야하는가를 계산함

줄은 종류가 2가지가 있음
1. 기존 점이 존재하는 줄
ㄴ 이놈은 기존 점 사이에 새로운 점을 찍기만 하면 됨

2. 기존 점 사이에 아예 새로 찍어야하는 줄
ㄴ 얘는 기존 점도 없으니까 기존 점도 찍고, 기존 점 사이에 새로운 점도 찍어야함

초기에 점은 4개이고 가로줄은 2줄임
총 가로줄의 개수를 n이라고 하면

1번의 경우, 점이 존재하는 가로줄은 n개이고 기존 점 사이 간격 개수 만큼 점을 찍으니까 n-1개
ㄴ n * (n-1)

2번의 경우, 새로운 가로줄은 기존 점 사이에 생기니까 n-1개이고 기존 점 사이 간격 개수 만큼 점을 찍는거 n-1개 외에 기존 점 n개도 포함해서 n+(n-1)개
ㄴ (n-1) * (n+(n-1))

점 계산이 끝나고 나면 가로줄의 개수가 기존 점 사이 간격만큼 늘어나니까 n = n+(n-1)가 됨. 이상!

*/

const fs = require('fs');
const input = fs.readFileSync(0, 'utf8').trim().split('\n');

const N = +input[0];
let n = 2, count = 4;

for (let i = 1; i <= N; i++) {
    count += n*(n-1) + (n-1)*(2*n-1);

    n = 2*n-1;
}

console.log(count);